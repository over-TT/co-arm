def tool_arm_detail(arguments: dict[str, Any]) -> list[dict[str, Any]]:
    """Crop the retained source capture without moving or recapturing."""

    expected = {"source_frame_id", "x", "y", "width", "height"}
    if set(arguments) != expected:
        raise ArmToolError(
            "arm_detail needs exactly source_frame_id, x, y, width and height."
        )
    source_frame_id = arguments.get("source_frame_id")
    if (
        not isinstance(source_frame_id, str)
        or not _SAFE_FRAME_ID.fullmatch(source_frame_id)
    ):
        raise ArmToolError("source_frame_id is not a valid retained camera frame id.")
    x = _bounded_number(arguments, "x", 0, 1, required=True)
    y = _bounded_number(arguments, "y", 0, 1, required=True)
    width = _bounded_number(
        arguments,
        "width",
        MIN_DETAIL_FRACTION,
        1,
        required=True,
    )
    height = _bounded_number(
        arguments,
        "height",
        MIN_DETAIL_FRACTION,
        1,
        required=True,
    )
    assert x is not None and y is not None and width is not None and height is not None
    if x + width > 1 or y + height > 1:
        raise ArmToolError("The normalized detail crop must stay inside the source frame.")
    if width * height > MAX_DETAIL_AREA_FRACTION:
        raise ArmToolError(
            f"The detail crop may cover at most {MAX_DETAIL_AREA_FRACTION:.0%} of the source frame."
        )

    image = _open_camera_jpeg(_load_kept_frame(source_frame_id))
    source_dimensions = {"width": image.width, "height": image.height}
    left = max(0, min(image.width - 1, math.floor(x * image.width)))
    top = max(0, min(image.height - 1, math.floor(y * image.height)))
    right = max(left + 1, min(image.width, math.ceil((x + width) * image.width)))
    bottom = max(top + 1, min(image.height, math.ceil((y + height) * image.height)))
    if right - left < 64 or bottom - top < 64:
        raise ArmToolError("The requested detail crop is too small to inspect reliably.")

    detail = image.crop((left, top, right, bottom))
    detail.thumbnail((DETAIL_MAX_DIMENSION, DETAIL_MAX_DIMENSION))
    output = io.BytesIO()
    detail.save(
        output,
        format="JPEG",
        quality=DETAIL_JPEG_QUALITY,
        optimize=True,
    )
    data = output.getvalue()
    detail_frame_id = _derived_frame_id("detail")
    saved = _keep_frame(detail_frame_id, data)
    context = {
        "frameId": detail_frame_id if saved else None,
        "sourceFrameId": source_frame_id,
        "view": "detail_crop",
        "sourceDimensions": source_dimensions,
        "returnedDimensions": {"width": detail.width, "height": detail.height},
        "crop": {
            "normalized": {"x": x, "y": y, "width": width, "height": height},
            "pixels": {
                "left": left,
                "top": top,
                "right": right,
                "bottom": bottom,
            },
        },
        "note": (
            "This is a crop of the retained source frame. No new "
            "photograph was taken and the arm did not move."
        ),
    }
    return [
        _text(json.dumps(context, indent=1)),
        {
            "type": "image",
            "data": base64.b64encode(data).decode("ascii"),
            "mimeType": "image/jpeg",
        },
    ]


def tool_arm_floor_guard(arguments: dict[str, Any]) -> list[dict[str, Any]]:
    enabled = arguments.get("enabled")
    if not isinstance(enabled, bool):
        raise ArmToolError("enabled must be true or false.", code="invalid_arguments")
    if enabled:
        if set(arguments) != {"enabled"}:
            raise ArmToolError(
                "Enabling the floor guard needs exactly enabled=true.",
                code="invalid_arguments",
            )
    elif (
        set(arguments) != {"enabled", "confirmed_floor_guard_disable"}
        or arguments.get("confirmed_floor_guard_disable") is not True
    ):
        raise ArmToolError(
            "confirmed_floor_guard_disable must be exactly true after the operator "
            "explicitly confirms disabling the physical floor keep-out guard.",
            code="confirmation_required",
        )
    state = GATEWAY.json("POST", "/api/robot/arm/floor-guard", {"enabled": enabled})
    guard = state.get("floorGuard") if isinstance(state.get("floorGuard"), dict) else {}
    return [
        _text(
            json.dumps(
                {
                    "floorGuard": guard,
                    "note": (
                        "The keep-out plane is back on. Poses that would reach "
                        "below it will be clamped again."
                        if enabled
                        else "The keep-out plane is OFF. Nothing now stops a pose "
                        "from driving the arm into the desk, so move in small "
                        "steps and check arm_state as you go. Turn it back on "
                        "with arm_floor_guard once this task is finished."
                    ),
                },
                indent=1,
            )
        )
    ]


def tool_arm_set_base_zero(arguments: dict[str, Any]) -> list[dict[str, Any]]:
    if (
        set(arguments) != {"confirmed_physical_zero"}
        or arguments.get("confirmed_physical_zero") is not True
    ):
        raise ArmToolError(
            "confirmed_physical_zero must be exactly true after the operator "
            "explicitly confirms Base is physically on its zero mark.",
            code="confirmation_required",
        )

    state = GATEWAY.json(
        "POST",
        "/api/robot/arm/joints/joint_1/calibrate",
        {"here": ["rawZero"]},
    )
    joints = state.get("joints")
    base_matches = (
        [joint for joint in joints if isinstance(joint, dict) and joint.get("id") == "joint_1"]
        if isinstance(joints, list)
        else []
    )
    base = base_matches[0] if len(base_matches) == 1 else {}
    degrees = base.get("degrees")
    healthy = (
        state.get("connection") == "online"
        and state.get("bus") == "online"
        and state.get("stopped") is False
        and state.get("collisionSuspected") is False
        and base.get("online") is True
        and isinstance(degrees, (int, float))
        and not isinstance(degrees, bool)
        and math.isfinite(float(degrees))
        and abs(float(degrees)) <= 0.05
    )
    if not healthy:
        raise ArmToolError(
            "The Pi calibration state did not prove a healthy, online joint_1 "
            "at 0 degrees with STOP clear and no collision. Base zero must be "
            "treated as unconfirmed."
        )

    return [
        _text(
            json.dumps(
                {
                    "baseZeroSet": True,
                    "joint": "base",
                    "jointId": "joint_1",
                    "degrees": float(degrees),
                    "connection": "online",
                    "bus": "online",
                    "physicalArmMotion": False,
                },
                indent=1,
            )
        )
    ]


