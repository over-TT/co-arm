"""Canonical Model Context Protocol server that hands the robot arm to Codex.

Codex spawns this file over stdio from an explicit machine-local MCP
configuration and speaks newline-delimited JSON-RPC 2.0 to it. Every tool here
is a thin call onto the arm gateway on the Pi, which is deliberate:
the floor guard, the calibration limits and the torque leases all live on the
Pi, so an agent driving through these tools is bound by exactly the same rules
as the operator dragging the 2D scene. The floor-guard tool may turn protection
off only when the operator explicitly asks; the host approval policy refuses an
autonomous disable and permits the model to turn protection back on.

Install the Python package and launch with ``python -m arm_mcp`` so the import
path does not depend on the working directory Codex happens to launch it from.
Nothing but JSON-RPC may ever reach stdout; diagnostics go to stderr.
"""

