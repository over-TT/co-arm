class ArmToolError(RuntimeError):
    """A tool failed in a way the model should read and react to."""

    def __init__(
        self,
        message: str,
        *,
        code: str = "arm_tool_error",
        retryable: bool = False,
        backend: dict[str, Any] | None = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.retryable = retryable
        self.backend = dict(backend) if backend is not None else None


def _log(message: str) -> None:
    print(f"[arm-mcp] {message}", file=sys.stderr, flush=True)


def _load_token() -> str:
    token_file = os.environ.get("ARM_GATEWAY_TOKEN_FILE", "").strip()
    if not token_file:
        raise ArmToolError(
            "ARM_GATEWAY_TOKEN_FILE is not set, so this tool server has no "
            "credential for the arm gateway.",
            code="configuration_error",
        )
    try:
        token = Path(token_file).read_text(encoding="utf-8").strip()
    except OSError as error:
        raise ArmToolError(
            f"Could not read the arm gateway token file: {error}",
            code="configuration_error",
        ) from error
    if not token:
        raise ArmToolError(
            "The arm gateway token file is empty.",
            code="configuration_error",
        )
    return token


class Gateway:
    """Authenticated HTTP access to the arm gateway, opened on first use."""

    def __init__(self, *, transport: httpx.BaseTransport | None = None) -> None:
        self._client: httpx.Client | None = None
        self._transport = transport
        self._expected_backend: str | None = None
        self._backend_identity: dict[str, Any] | None = None

    def client(self) -> httpx.Client:
        if self._client is None:
            try:
                base_url = validated_loopback_gateway_url(
                    os.environ.get("ARM_GATEWAY_URL", DEFAULT_GATEWAY_URL)
                )
                expected_backend = validated_expected_backend(
                    os.environ.get("ARM_EXPECTED_BACKEND")
                )
            except GatewayConfigurationError as error:
                raise ArmToolError(
                    f"Invalid arm gateway configuration: {error}",
                    code="configuration_error",
                ) from error
            token = _load_token()
            self._client = httpx.Client(
                base_url=base_url,
                headers={
                    "Authorization": f"Bearer {token}",
                    "Accept": "application/json",
                },
                timeout=httpx.Timeout(READ_TIMEOUT_SECONDS, connect=CONNECT_TIMEOUT_SECONDS),
                follow_redirects=False,
                trust_env=False,
                transport=self._transport,
            )
            self._expected_backend = expected_backend
        return self._client

    def backend_identity(self) -> dict[str, Any] | None:
        """Return only identity proved by the latest authenticated health check."""

        return dict(self._backend_identity) if self._backend_identity is not None else None

    def verify_backend(self) -> dict[str, Any]:
        """Authenticate and validate ``/healthz`` before an operational call."""

        response = self._request_once("GET", "/healthz", None)
        return self._accept_backend_health(response)

    def _accept_backend_health(self, response: httpx.Response) -> dict[str, Any]:
        """Validate one authenticated health document and retain its identity."""

        try:
            document = response.json()
        except ValueError as error:
            raise ArmToolError(
                "The arm gateway health response was not JSON.",
                code="backend_identity_invalid",
            ) from error
        if not isinstance(document, dict):
            raise ArmToolError(
                "The arm gateway health response was not an object.",
                code="backend_identity_invalid",
            )

        backend_id = document.get("backendId")
        instance_id = document.get("backendInstanceId")
        simulated = document.get("simulated")
        status = document.get("status")
        actual = (
            {
                "backendId": backend_id,
                "backendInstanceId": instance_id,
                "simulated": simulated,
            }
            if backend_id in {"sim", "real"}
            and isinstance(instance_id, str)
            and _SAFE_BACKEND_INSTANCE_ID.fullmatch(instance_id) is not None
            and isinstance(simulated, bool)
            else None
        )
        if (
            status != "ok"
            or actual is None
            or (backend_id == "sim") is not simulated
        ):
            raise ArmToolError(
                "The arm gateway did not return a coherent backend identity from /healthz.",
                code="backend_identity_invalid",
                backend=actual,
            )

        expected_backend = self._expected_backend
        if expected_backend is None:
            self.client()
            expected_backend = self._expected_backend
        assert expected_backend in {"sim", "real"}
        if backend_id != expected_backend:
            raise ArmToolError(
                "The authenticated gateway proved backend "
                f"{backend_id!r}, but ARM_EXPECTED_BACKEND is {expected_backend!r}. "
                "No operational request was sent.",
                code="backend_mismatch",
                backend=actual,
            )

        self._backend_identity = actual
        return dict(actual)

    def request(
        self,
        method: str,
        path: str,
        payload: dict[str, Any] | None = None,
        *,
        read_timeout_seconds: float | None = None,
    ) -> httpx.Response:
        if path == "/healthz":
            response = self._request_once(
                method,
                path,
                payload,
                read_timeout_seconds=read_timeout_seconds,
            )
            self._accept_backend_health(response)
            return response
        self.verify_backend()
        return self._request_once(
            method,
            path,
            payload,
            read_timeout_seconds=read_timeout_seconds,
        )

    def _request_once(
        self,
        method: str,
        path: str,
        payload: dict[str, Any] | None = None,
        *,
        read_timeout_seconds: float | None = None,
    ) -> httpx.Response:
        try:
            response = self._send_once(
                method,
                path,
                payload,
                read_timeout_seconds=read_timeout_seconds,
            )
        except httpx.ConnectError as error:
            raise ArmToolError(
                "The configured arm gateway is not reachable: nothing is listening "
                "on its local loopback port.",
                code="gateway_unreachable",
                retryable=True,
            ) from error
        except httpx.TimeoutException as error:
            raise ArmToolError(
                "The configured arm gateway accepted the connection but did not "
                "answer in time.",
                code="gateway_timeout",
                retryable=True,
            ) from error
        except httpx.HTTPError as error:
            raise ArmToolError(
                f"The arm gateway call failed: {error}",
                code="gateway_transport_error",
                retryable=True,
            ) from error
        if response.status_code >= 400:
            raise ArmToolError(
                f"The arm gateway refused this ({response.status_code}): "
                f"{_detail_of(response)}",
                code="gateway_refused",
                retryable=response.status_code >= 500,
            )
        return response

    def _send_once(
        self,
        method: str,
        path: str,
        payload: dict[str, Any] | None,
        *,
        read_timeout_seconds: float | None = None,
    ) -> httpx.Response:
        """Send one request, retrying only a response-less safe read once.

        A connection the gateway closed while it sat idle in the pool fails with
        no response at all. Repeating GET/HEAD is safe, but replaying a POST is
        not: a one-use plan or sequence may already have moved the arm before
        its response was lost. Those writes return an explicit outcome-unknown
        error and must be reconciled from fresh state instead of redispatched.
        """

        timeout = (
            httpx.Timeout(read_timeout_seconds, connect=CONNECT_TIMEOUT_SECONDS)
            if read_timeout_seconds is not None
            else self.client().timeout
        )
        try:
            return self.client().request(method, path, json=payload, timeout=timeout)
        except httpx.RemoteProtocolError as error:
            if method.upper() in {"GET", "HEAD"}:
                return self.client().request(method, path, json=payload, timeout=timeout)
            raise ArmToolError(
                "The gateway connection closed before it returned a response to this write. "
                "The physical outcome is unknown; the request was not replayed. Read fresh "
                "arm_state (and arm_scene when route geometry matters) before deciding on "
                "another action.",
                code="gateway_response_lost",
                retryable=False,
                backend=self.backend_identity(),
            ) from error

    def json(
        self,
        method: str,
        path: str,
        payload: dict[str, Any] | None = None,
        *,
        read_timeout_seconds: float | None = None,
    ) -> dict[str, Any]:
        response = self.request(
            method,
            path,
            payload,
            read_timeout_seconds=read_timeout_seconds,
        )
        try:
            body = response.json()
        except ValueError as error:
            raise ArmToolError("The arm gateway returned a response that was not JSON.") from error
        if not isinstance(body, dict):
            raise ArmToolError("The arm gateway returned an unexpected response shape.")
        return body

    def camera_frame(self, path: str) -> tuple[bytes, httpx.Headers]:
        """Stream one JPEG into a hard-bounded buffer and preserve evidence headers."""

        self.verify_backend()
        try:
            with self.client().stream("GET", path) as response:
                if response.status_code >= 400:
                    raise ArmToolError(
                        f"The arm gateway refused the camera frame ({response.status_code})."
                    )
                declared = response.headers.get("content-length")
                declared_length: int | None = None
                if declared is not None:
                    normalized = declared.strip()
                    if not normalized.isdigit():
                        raise ArmToolError(
                            "The camera frame returned an invalid Content-Length."
                        )
                    declared_length = int(normalized)
                    if not 1 <= declared_length <= MAX_RETAINED_FRAME_BYTES:
                        raise ArmToolError(
                            "The camera frame exceeded the 16 MiB transfer limit."
                        )
                body = bytearray()
                for chunk in response.iter_bytes():
                    body.extend(chunk)
                    if len(body) > MAX_RETAINED_FRAME_BYTES:
                        raise ArmToolError(
                            "The camera frame exceeded the 16 MiB transfer limit."
                        )
                if not body:
                    raise ArmToolError("The camera frame was empty.")
                if declared_length is not None and declared_length != len(body):
                    raise ArmToolError(
                        "The camera frame length did not match Content-Length."
                    )
                return bytes(body), httpx.Headers(response.headers)
        except ArmToolError:
            raise
        except httpx.ConnectError as error:
            raise ArmToolError(
                "The configured arm gateway is not reachable: nothing is listening "
                "on its local loopback port.",
                code="gateway_unreachable",
                retryable=True,
            ) from error
        except httpx.TimeoutException as error:
            raise ArmToolError(
                "The configured arm gateway accepted the camera request but did not answer in time.",
                code="gateway_timeout",
                retryable=True,
            ) from error
        except httpx.HTTPError as error:
            raise ArmToolError(
                f"The camera frame transfer failed: {error}",
                code="gateway_transport_error",
                retryable=True,
            ) from error


def _detail_of(response: httpx.Response) -> str:
    try:
        body = response.json()
    except ValueError:
        return response.text[:300] or "no detail supplied"
    if isinstance(body, dict) and isinstance(body.get("detail"), str):
        return body["detail"]
    return json.dumps(body)[:300]


