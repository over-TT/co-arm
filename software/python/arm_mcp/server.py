def _open_camera_jpeg(data: bytes) -> Any:
    try:
        from PIL import Image
    except ImportError as error:  # pragma: no cover - deployment dependency failure
        raise ArmToolError("Camera survey and detail views need Pillow in the web environment.") from error
    try:
        image = Image.open(io.BytesIO(data))
        image.load()
        return image.convert("RGB")
    except Exception:
        raise ArmToolError("The retained camera frame is not a readable JPEG.") from None


def _survey_camera_jpeg(
    data: bytes,
    source_dimensions: dict[str, int],
) -> tuple[bytes, dict[str, int], bool]:
    """Return a smaller survey payload while preserving the full retained frame."""

    width, height = source_dimensions.get("width"), source_dimensions.get("height")
    if (
        isinstance(width, int)
        and isinstance(height, int)
        and width <= SURVEY_MAX_WIDTH
        and height <= SURVEY_MAX_HEIGHT
    ):
        return data, source_dimensions, False

    image = _open_camera_jpeg(data)
    image.thumbnail((SURVEY_MAX_WIDTH, SURVEY_MAX_HEIGHT))
    output = io.BytesIO()
    image.save(
        output,
        format="JPEG",
        quality=SURVEY_JPEG_QUALITY,
        optimize=True,
    )
    return (
        output.getvalue(),
        {"width": image.width, "height": image.height},
        True,
    )


def _derived_frame_id(kind: str) -> str:
    return f"{kind}-{int(time.time() * 1000)}-{secrets.token_hex(4)}"


def _clamp_note(clamped: set[str]) -> str:
    """Say which rule stopped the arm, because they have different answers.

    The floor plane only ever touches the shoulder and the elbow -- they are the
    two joints that decide how low the arm reaches. A base or camera angle can
    only ever be cut short by that joint's own calibrated travel. Reporting both
    as "the floor guard" sent the model looking for a way to reach lower when
    what it had actually done was ask the base to turn further than it can.
    """

    if not clamped:
        return (
            "Move commands were sent. The joints are still travelling; call "
            "arm_state to read where they actually are."
        )
    floor_related = clamped & set(FLOOR_JOINTS)
    travel_only = clamped - floor_related
    parts: list[str] = []
    if floor_related:
        parts.append(
            "The "
            + " and ".join(sorted(JOINT_TO_FRIENDLY[joint] for joint in floor_related))
            + " stopped short, held by the floor keep-out plane on the Pi or by that "
            "joint's own travel limit. The arm stopped at the boundary instead of "
            "going through it, which is the system working."
        )
    if travel_only:
        parts.append(
            "The "
            + " and ".join(sorted(JOINT_TO_FRIENDLY[joint] for joint in travel_only))
            + " was asked to go outside its calibrated travel, so it stopped at the "
            "end of its range. The floor plane has nothing to do with this joint."
        )
    return " ".join(parts)


def _pose_snapshot(value: Any) -> list[dict[str, Any]]:
    if isinstance(value, dict) and isinstance(value.get("joints"), list):
        return _pose(value)
    if isinstance(value, dict):
        summary: list[dict[str, Any]] = []
        for joint_id in JOINT_TO_FRIENDLY:
            degrees = value.get(joint_id)
            if (
                isinstance(degrees, (int, float))
                and not isinstance(degrees, bool)
                and math.isfinite(float(degrees))
            ):
                summary.append(
                    {
                        "joint": JOINT_TO_FRIENDLY[joint_id],
                        "degrees": float(degrees),
                    }
                )
        return summary
    if isinstance(value, list):
        return [dict(row) for row in value if isinstance(row, dict)]
    return []


def _pose_near_capture_report(value: Any) -> Any:
    if isinstance(value, dict) and ("before" in value or "after" in value):
        return {
            "before": _pose_snapshot(value.get("before")),
            "after": _pose_snapshot(value.get("after")),
        }
    return _pose_snapshot(value)


def _camera_frame_content(
    capture: dict[str, Any],
    view: str,
    *,
    pose_near_capture: Any = None,
    extra_context: dict[str, Any] | None = None,
    require_one_use_transfer: bool = False,
) -> list[dict[str, Any]]:
    if view not in {"survey", "detail"}:
        raise ArmToolError("view must be survey or detail.")
    source_frame_id = capture.get("frameId")
    if (
        not isinstance(source_frame_id, str)
        or not _SAFE_FRAME_ID.fullmatch(source_frame_id)
    ):
        raise ArmToolError("The camera captured a frame but returned no frame id.")
    capture_profile = capture.get("captureProfile")
    if capture_profile not in {"survey", "detail"}:
        raise ArmToolError("The camera returned no valid capture profile.")
    if capture_profile != view:
        raise ArmToolError("The camera returned a different profile than the requested view.")
    declared_byte_count = capture.get("byteCount")
    if (
        isinstance(declared_byte_count, bool)
        or not isinstance(declared_byte_count, int)
        or not 1 <= declared_byte_count <= MAX_RETAINED_FRAME_BYTES
    ):
        raise ArmToolError("The camera returned an invalid frame byte count.")
    frame_path = f"/api/camera/frames/{source_frame_id}"
    if require_one_use_transfer:
        transfer_token = capture.get("transferToken")
        content_digest = capture.get("contentSha256")
        raw_digest = capture.get("sha256")
        if (
            not isinstance(transfer_token, str)
            or not _SAFE_FRAME_ID.fullmatch(transfer_token)
        ):
            raise ArmToolError(
                "The composed camera action returned no safe one-use transfer token."
            )
        expected_transfer_path = f"/api/camera/transfers/{transfer_token}"
        if (
            capture.get("oneUse") is not True
            or capture.get("transferUrl") != expected_transfer_path
            or capture.get("frameUrl") != expected_transfer_path
        ):
            raise ArmToolError(
                "The composed camera action returned mismatched transfer metadata."
            )
        if (
            not isinstance(content_digest, str)
            or not _SAFE_PLAN_DIGEST.fullmatch(content_digest)
            or not isinstance(raw_digest, str)
            or not _SAFE_RAW_SHA256.fullmatch(raw_digest)
            or content_digest != f"sha256:{raw_digest}"
        ):
            raise ArmToolError(
                "The composed camera action returned invalid transfer digest evidence."
            )
        frame_path = expected_transfer_path
    # Ordinary captures are fetched immediately from bounded history. Composed
    # captures use a separately bounded, opaque, one-use transfer so unrelated
    # dashboard captures cannot evict or consume the pose-bound JPEG.
    original, frame_headers = GATEWAY.camera_frame(frame_path)
    if (
        not 1 <= len(original) <= MAX_RETAINED_FRAME_BYTES
        or len(original) != declared_byte_count
    ):
        raise ArmToolError(
            "The downloaded JPEG length did not match the bounded camera metadata."
        )
    if require_one_use_transfer:
        expected_digest = capture["contentSha256"]
        actual_digest = f"sha256:{hashlib.sha256(original).hexdigest()}"
        if (
            frame_headers.get("x-frame-id") != source_frame_id
            or frame_headers.get("x-content-sha256") != expected_digest
            or frame_headers.get("etag") != f'"{expected_digest}"'
            or frame_headers.get("x-one-use-transfer") != "true"
            or not secrets.compare_digest(actual_digest, expected_digest)
        ):
            raise ArmToolError(
                "The one-use camera transfer did not match its pose-bound frame evidence."
            )
    source_saved = _keep_frame(source_frame_id, original)
    source_dimensions = _camera_dimensions(capture.get("dimensions"))
    returned = original
    returned_dimensions = source_dimensions
    transformed = False
    if view == "survey":
        returned, returned_dimensions, transformed = _survey_camera_jpeg(
            original,
            source_dimensions,
        )

    display_frame_id: str | None = source_frame_id if source_saved else None
    if transformed:
        survey_frame_id = _derived_frame_id("survey")
        display_frame_id = (
            survey_frame_id if _keep_frame(survey_frame_id, returned) else None
        )
    encoded = base64.b64encode(returned).decode("ascii")

    legacy_pose: list[dict[str, Any]] | None = None
    measured_near_capture: Any = None
    if pose_near_capture is None:
        try:
            state = GATEWAY.json("GET", "/api/robot/arm/state")
            legacy_pose = _pose(state)
        except ArmToolError:
            legacy_pose = []
    else:
        measured_near_capture = _pose_near_capture_report(pose_near_capture)

    autofocus = _capture_autofocus(capture.get("autofocus"))
    focus_quality = _capture_focus_quality(capture.get("focusQuality"))
    camera_profile = _capture_camera_profile(capture.get("cameraProfile"))
    if autofocus is None or autofocus.get("capability") == "unknown":
        focus_note = " Focus capability is unknown; judge the subject from the returned pixels."
    elif autofocus.get("capability") == "supported":
        focus_note = (
            " Motorized autofocus is supported; use its same-frame state and lens "
            "position as supporting evidence, while visible subject detail remains decisive."
        )
    else:
        focus_note = (
            " This source reports no motorized autofocus support; use visible subject "
            "detail rather than assuming a particular physical lens mechanism."
        )
    detail_is_native = bool(
        camera_profile
        and camera_profile["captureProfiles"]["detail"]
        == camera_profile["nativeDimensions"]
    )
    detail_profile_note = (
        "native-detail profile" if detail_is_native else "detail profile"
    )
    context = {
        # Echoed back so the operator's chat can show the same photograph the
        # model is looking at. The gateway only keeps eight frames, so the copy
        # written by _keep_frame is what the UI actually loads.
        "frameId": display_frame_id,
        "sourceFrameId": source_frame_id if source_saved else None,
        "capturedAt": capture.get("capturedAt"),
        "view": view,
        "captureProfile": capture_profile,
        "dimensions": source_dimensions,
        "returnedDimensions": returned_dimensions,
        "note": (
            "This is the arm's own camera, software-rotated 180 degrees so the "
            "delivered frame is upright. Camera joint 0 deg points straight "
            "down the forearm, so at 0 the camera looks wherever the arm is "
            "pointing. Survey uses the camera's fast wide profile and returns at "
            "most 1280 x 720 while retaining that source for arm_detail; detail "
            f"requests the camera's {detail_profile_note}."
            + focus_note
        ),
    }
    if legacy_pose is not None:
        # Kept for the standalone camera tool's existing response contract. It
        # is sampled after capture, so it is contextual rather than exact.
        context["poseAtCapture"] = legacy_pose
    else:
        context["measuredPoseNearCapture"] = measured_near_capture
        context["note"] += (
            " For this combined action, the Pi proved arrival from distinct fresh "
            "telemetry samples and validated measured pose immediately before and "
            "after capture."
        )
    if extra_context:
        context.update(extra_context)
    if autofocus is not None:
        context["autofocus"] = autofocus
    if focus_quality is not None:
        context["focusQuality"] = focus_quality
    if camera_profile is not None:
        context["cameraProfile"] = camera_profile
    desk_projection = _camera_desk_projection(
        capture,
        camera_profile,
        pose_near_capture,
    )
    if desk_projection is not None:
        context["deskProjection"] = desk_projection
    return [
        _text(json.dumps(context, indent=1)),
        {"type": "image", "data": encoded, "mimeType": "image/jpeg"},
    ]


