def _current_backend_identity() -> dict[str, Any] | None:
    getter = getattr(GATEWAY, "backend_identity", None)
    if not callable(getter):
        return None
    identity = getter()
    return dict(identity) if isinstance(identity, dict) else None


def _structured_success_content(
    content: list[dict[str, Any]],
    backend: dict[str, Any] | None,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Keep human text and machine output on one backend-labelled document."""

    decorated = [dict(block) for block in content]
    data: dict[str, Any] | None = None
    for index, block in enumerate(decorated):
        if block.get("type") != "text" or not isinstance(block.get("text"), str):
            continue
        try:
            parsed = json.loads(block["text"])
        except ValueError:
            parsed = None
        if isinstance(parsed, dict):
            data = dict(parsed)
            if backend is not None:
                data["backend"] = dict(backend)
            decorated[index] = {
                **block,
                "text": json.dumps(data, indent=1, allow_nan=False),
            }
            break
        if data is None:
            data = {"message": block["text"]}
    if data is None:
        data = {"contentTypes": [str(block.get("type")) for block in decorated]}
    return decorated, data


def _tool_error_result(
    name: str,
    message: str,
    *,
    code: str,
    retryable: bool = False,
    backend: dict[str, Any] | None = None,
) -> dict[str, Any]:
    identity = dict(backend) if backend is not None else _current_backend_identity()
    error = {"code": code, "message": message, "retryable": retryable}
    error_text = _text(message)
    error_text["annotations"] = {"audience": ["assistant"], "priority": 1.0}
    metadata: dict[str, Any] = {"co-arm/error": error}
    if identity is not None:
        metadata["co-arm/backend"] = identity
    return {
        "content": [error_text],
        "structuredContent": {
            "ok": False,
            "tool": name,
            "backend": identity,
            "error": error,
        },
        "isError": True,
        "_meta": metadata,
    }


def call_tool(name: str, arguments: dict[str, Any]) -> dict[str, Any]:
    handler = HANDLERS.get(name)
    if handler is None:
        return _tool_error_result(
            name,
            f"There is no tool called {name}.",
            code="unknown_tool",
        )
    try:
        content = handler(arguments)
        backend = _current_backend_identity()
        decorated, data = _structured_success_content(content, backend)
        metadata = {"co-arm/backend": backend} if backend is not None else {}
        return {
            "content": decorated,
            "structuredContent": {
                "ok": True,
                "tool": name,
                "backend": backend,
                "data": data,
            },
            "isError": False,
            "_meta": metadata,
        }
    except ArmToolError as error:
        return _tool_error_result(
            name,
            str(error),
            code=error.code,
            retryable=error.retryable,
            backend=error.backend,
        )
    except Exception as error:  # noqa: BLE001 - a crash here would kill the tool server
        _log(f"{name} raised {type(error).__name__}: {error}")
        return _tool_error_result(
            name,
            f"The {name} tool failed unexpectedly. Check the MCP server diagnostics.",
            code="internal_error",
        )


def handle(message: dict[str, Any]) -> dict[str, Any] | None:
    method = message.get("method")
    request_id = message.get("id")
    params = message.get("params") if isinstance(message.get("params"), dict) else {}

    # Notifications carry no id and must never be answered.
    if request_id is None:
        return None

    if method == "initialize":
        requested = params.get("protocolVersion")
        version = requested if requested in SUPPORTED_PROTOCOL_VERSIONS else PROTOCOL_VERSION
        return _ok(
            request_id,
            {
                "protocolVersion": version,
                "capabilities": {"tools": {"listChanged": False}},
                "serverInfo": {"name": SERVER_NAME, "version": SERVER_VERSION},
            },
        )
    if method == "tools/list":
        return _ok(request_id, {"tools": TOOLS})
    if method == "tools/call":
        name = params.get("name")
        if not isinstance(name, str):
            return _error(request_id, -32602, "tools/call needs a tool name.")
        raw_arguments = params.get("arguments", {})
        if not isinstance(raw_arguments, dict):
            return _ok(
                request_id,
                _tool_error_result(
                    name,
                    "tools/call arguments must be an object.",
                    code="invalid_arguments",
                ),
            )
        arguments = raw_arguments
        return _ok(request_id, call_tool(name, arguments))
    if method == "ping":
        return _ok(request_id, {})
    if method in {"resources/list", "prompts/list"}:
        # Answered rather than refused so a client that probes them on connect
        # does not log this server as broken.
        return _ok(request_id, {"resources": [], "prompts": []})
    return _error(request_id, -32601, f"Method {method} is not supported.")


def _ok(request_id: Any, result: dict[str, Any]) -> dict[str, Any]:
    return {"jsonrpc": "2.0", "id": request_id, "result": result}


def _error(request_id: Any, code: int, message: str) -> dict[str, Any]:
    return {"jsonrpc": "2.0", "id": request_id, "error": {"code": code, "message": message}}


def serve(stdin: Any = None, stdout: Any = None) -> None:
    source = stdin if stdin is not None else sys.stdin
    sink = stdout if stdout is not None else sys.stdout
    _log("ready")
    for line in source:
        line = line.strip()
        if not line:
            continue
        try:
            message = json.loads(line)
        except json.JSONDecodeError:
            _log("dropped a line that was not JSON")
            continue
        if not isinstance(message, dict):
            continue
        try:
            response = handle(message)
        except Exception as error:  # noqa: BLE001 - stay alive for the next request
            _log(f"handler crashed: {type(error).__name__}: {error}")
            response = _error(message.get("id"), -32603, "The arm tool server hit an internal error.")
        if response is None:
            continue
        sink.write(json.dumps(response, separators=(",", ":")) + "\n")
        sink.flush()


if __name__ == "__main__":
    serve()
