def _render_plan_jpeg(plan: dict[str, Any]) -> bytes:
    """Render the measured arm solid and the prepared pose as a dashed ghost."""

    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError as error:  # pragma: no cover - dependency error is environment-specific
        raise ArmToolError("The 2D plan renderer needs Pillow in the web environment.") from error

    scene = plan.get("scene")
    if not isinstance(scene, dict):
        raise ArmToolError("The prepared plan did not include a 2D scene.")
    measured = scene.get("measured")
    resolved = scene.get("resolved")
    geometry = scene.get("geometryMm")
    floor_guard = scene.get("floorGuard")
    if not all(isinstance(value, dict) for value in (measured, resolved, geometry, floor_guard)):
        raise ArmToolError("The prepared plan returned an incomplete 2D scene.")
    assert isinstance(measured, dict) and isinstance(resolved, dict)
    measured_points = measured.get("points")
    resolved_points = resolved.get("points")
    measured_servo = measured.get("servoDegrees")
    measured_model = measured.get("modelDegrees")
    if not all(
        isinstance(value, dict)
        for value in (measured_points, resolved_points, measured_servo, measured_model)
    ):
        raise ArmToolError("The prepared plan returned incomplete measured/resolved geometry.")
    assert isinstance(measured_servo, dict) and isinstance(measured_model, dict)

    # Reuse the measured-only renderer so the live scene and plan preview share
    # one coordinate frame. The prepared pose is then painted as a ghost over it.
    live_scene = {
        "points": measured_points,
        "geometryMm": geometry,
        "floorGuard": floor_guard,
        "measuredServoDegrees": {
            friendly: measured_servo.get(joint_id) for friendly, joint_id in JOINTS.items()
        },
        "modelDegrees": measured_model,
    }
    image = Image.open(io.BytesIO(_render_scene_jpeg(live_scene))).convert("RGB")
    draw = ImageDraw.Draw(image)
    font = ImageFont.load_default()
    width, height = image.size
    reach = (
        float(geometry["upperArmMm"])
        + float(geometry["distalMm"])
        + SCENE_RAY_MM
    )
    floor_mm = float(floor_guard["floorMm"])
    world_x_min, world_x_max = -reach, reach
    world_z_min = min(-30.0, floor_mm - 70.0)
    world_z_max = (
        float(geometry["baseHeightMm"])
        + float(geometry["upperArmMm"])
        + float(geometry["distalMm"])
        + 60.0
    )
    pad_left, pad_right, pad_top, pad_bottom = 70.0, 270.0, 55.0, 55.0
    scale = min(
        (width - pad_left - pad_right) / (world_x_max - world_x_min),
        (height - pad_top - pad_bottom) / (world_z_max - world_z_min),
    )

    def px(point: Any) -> tuple[float, float]:
        if not isinstance(point, dict):
            raise ArmToolError("The prepared plan returned an invalid 2D point.")
        radial = point.get("radialMm")
        vertical = point.get("heightMm")
        if not all(
            isinstance(value, (int, float))
            and not isinstance(value, bool)
            and math.isfinite(float(value))
            for value in (radial, vertical)
        ):
            raise ArmToolError("The prepared plan returned a non-finite 2D point.")
        return (
            pad_left + (float(radial) - world_x_min) * scale,
            height - pad_bottom - (float(vertical) - world_z_min) * scale,
        )

    def dashed(start: tuple[float, float], end: tuple[float, float], color: str, width_px: int) -> None:
        segments = 16
        for index in range(0, segments, 2):
            low = index / segments
            high = min(1.0, (index + 1) / segments)
            draw.line(
                (
                    start[0] + (end[0] - start[0]) * low,
                    start[1] + (end[1] - start[1]) * low,
                    start[0] + (end[0] - start[0]) * high,
                    start[1] + (end[1] - start[1]) * high,
                ),
                fill=color,
                width=width_px,
            )

    assert isinstance(resolved_points, dict)
    base = px(resolved_points.get("base"))
    shoulder = px(resolved_points.get("shoulder"))
    elbow = px(resolved_points.get("elbow"))
    tip = px(resolved_points.get("tipCamera"))
    for start, end in ((base, shoulder), (shoulder, elbow), (elbow, tip)):
        dashed(start, end, "#24e4ff", 9)
    for x, y in (base, shoulder, elbow, tip):
        draw.ellipse((x - 8, y - 8, x + 8, y + 8), outline="#7df2ff", width=3)
    ray = resolved_points.get("cameraRayEnd")
    if isinstance(ray, dict):
        dashed(tip, px(ray), "#54e4bc", 4)

    draw.rectangle((20, 16, 365, 42), fill="#071015")
    draw.text((24, 20), "ARM ALLIANCE / PLAN PREVIEW", fill="#91e7ff", font=font)
    draw.text((72, height - 38), "solid = measured    dashed cyan = planned", fill="#a8c1cc", font=font)

    # Replace the lower half of the measured-only information panel with the
    # exact prepared joint values and the one-use confirmation details.
    panel_x = width - 245
    draw.rectangle((panel_x + 10, 278, width - 30, height - 40), fill="#0c1a21")
    resolved_pose = plan.get("resolvedPose")
    measured_pose = plan.get("measuredPose")
    if not isinstance(resolved_pose, dict) or not isinstance(measured_pose, dict):
        raise ArmToolError("The prepared plan returned no measured/resolved pose numbers.")
    lines = ["PLANNED SERVO DEGREES"]
    for friendly, joint_id in JOINTS.items():
        before = measured_pose.get(joint_id)
        after = resolved_pose.get(joint_id)
        if isinstance(before, (int, float)) and isinstance(after, (int, float)):
            lines.append(f"{friendly:<9} {before:+6.1f} -> {after:+6.1f}")
        else:
            lines.append(f"{friendly:<9} unavailable")
    clearance = plan.get("lowestClearanceMm")
    if isinstance(clearance, (int, float)) and not isinstance(clearance, bool):
        lines.extend(("", f"clearance  {float(clearance):7.1f} mm"))
    warnings = plan.get("warnings")
    if isinstance(warnings, list) and warnings:
        lines.extend(("", f"warnings   {len(warnings)} (read text)"))
    lines.extend(("", "PREVIEW ONLY - NOT MOVED"))
    y = 292
    for line in lines:
        color = "#f4c66d" if line.startswith("PREVIEW") or line.startswith("warnings") else "#b7ccd5"
        draw.text((panel_x + 18, y), line, fill=color, font=font)
        y += 22

    buffer = io.BytesIO()
    image.save(buffer, format="JPEG", quality=90, optimize=True)
    return buffer.getvalue()


def _requested_targets(arguments: dict[str, Any]) -> dict[str, float]:
    targets: dict[str, float] = {}
    for friendly, joint_id in JOINTS.items():
        value = arguments.get(friendly)
        if value is None:
            continue
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise ArmToolError(f"{friendly} must be a number of degrees.")
        targets[joint_id] = float(value)
    return targets


def _bounded_number(
    arguments: dict[str, Any],
    name: str,
    minimum: float,
    maximum: float,
    *,
    required: bool = False,
) -> float | None:
    value = arguments.get(name)
    if value is None:
        if required:
            raise ArmToolError(f"{name} is required.")
        return None
    if (
        isinstance(value, bool)
        or not isinstance(value, (int, float))
        or not math.isfinite(float(value))
    ):
        raise ArmToolError(f"{name} must be a finite number.")
    bounded = float(value)
    if bounded < minimum or bounded > maximum:
        raise ArmToolError(f"{name} must be between {minimum:g} and {maximum:g}.")
    return bounded


def _capture_autofocus(value: Any) -> dict[str, Any] | None:
    """Keep only the bounded autofocus facts the camera contract defines."""

    if not isinstance(value, dict):
        return None
    allowed = {
        "capability": {"unknown", "supported", "unsupported"},
        "mode": {"unknown", "continuous", "fixed"},
        "state": {
            "not_started",
            "configured",
            "configuration_failed",
            "fixed",
            "idle",
            "scanning",
            "focused",
            "failed",
            "closed",
        },
        "range": {"unavailable", "normal", "full", "macro"},
    }
    cleaned: dict[str, Any] = {}
    for key, values in allowed.items():
        candidate = value.get(key)
        if candidate not in values:
            return None
        cleaned[key] = candidate
    lens = value.get("lensPosition")
    if lens is not None:
        if (
            isinstance(lens, bool)
            or not isinstance(lens, (int, float))
            or not math.isfinite(float(lens))
        ):
            return None
        cleaned["lensPosition"] = float(lens)
    return cleaned


def _capture_focus_quality(value: Any) -> dict[str, Any] | None:
    """Keep only the strict, relative-only same-frame FocusFoM contract."""

    if not isinstance(value, dict):
        return None
    status = value.get("status")
    measured = value.get("value")
    if (
        value.get("metric") != "libcamera_focus_fom"
        or status not in {"measured", "unavailable"}
        or value.get("higherIsSharper") is not True
        or value.get("comparison") != "same_subject_similar_framing_only"
        or "value" not in value
    ):
        return None
    if status == "unavailable":
        if measured is not None:
            return None
        bounded_value: int | None = None
    else:
        if (
            isinstance(measured, bool)
            or not isinstance(measured, int)
            or not 0 <= measured <= 2_147_483_647
        ):
            return None
        bounded_value = measured
    return {
        "metric": "libcamera_focus_fom",
        "status": status,
        "value": bounded_value,
        "higherIsSharper": True,
        "comparison": "same_subject_similar_framing_only",
    }


def tool_arm_plan(arguments: dict[str, Any]) -> list[dict[str, Any]]:
    """Prepare a one-use physical pose without taking torque or moving."""

    targets = _requested_targets(arguments)
    for joint_id, value in targets.items():
        if not math.isfinite(value) or value < PLAN_ANGLE_MIN or value > PLAN_ANGLE_MAX:
            friendly = JOINT_TO_FRIENDLY[joint_id]
            raise ArmToolError(
                f"{friendly} must be between {PLAN_ANGLE_MIN:g} and {PLAN_ANGLE_MAX:g} degrees."
            )

    radial_present = arguments.get("radial_mm") is not None
    height_present = arguments.get("height_mm") is not None
    if radial_present != height_present:
        raise ArmToolError("radial_mm and height_mm must be supplied together for tip IK.")
    tip: dict[str, float] | None = None
    if radial_present:
        radial = _bounded_number(
            arguments, "radial_mm", PLAN_RADIAL_MIN_MM, PLAN_RADIAL_MAX_MM, required=True
        )
        height = _bounded_number(
            arguments, "height_mm", PLAN_HEIGHT_MIN_MM, PLAN_HEIGHT_MAX_MM, required=True
        )
        assert radial is not None and height is not None
        if "joint_2" in targets or "joint_3" in targets:
            raise ArmToolError(
                "Tip IK owns shoulder and elbow. Name only base/camera alongside radial_mm and height_mm."
            )
        tip = {"radialMm": radial, "heightMm": height}
    if not targets and tip is None:
        raise ArmToolError(
            "Name at least one joint to plan, or provide radial_mm and height_mm for tip IK."
        )

    preference = arguments.get("elbow_preference", "nearest")
    if preference not in {"nearest", "up", "down"}:
        raise ArmToolError("elbow_preference must be nearest, up or down.")
    request: dict[str, Any] = {
        "targets": targets,
        "elbowPreference": preference,
    }
    if tip is not None:
        request["tip"] = tip
    plan = GATEWAY.json("POST", "/api/robot/arm/plans/preview", request)
    plan_id = plan.get("planId")
    digest = plan.get("planDigest")
    if not isinstance(plan_id, str) or not _SAFE_PLAN_ID.fullmatch(plan_id):
        raise ArmToolError("The gateway prepared a plan but returned an invalid plan id.")
    if not isinstance(digest, str) or not _SAFE_PLAN_DIGEST.fullmatch(digest):
        raise ArmToolError("The gateway prepared a plan but returned an invalid digest.")

    payload = {
        **plan,
        "note": (
            "PREVIEW ONLY: no torque was taken and the arm did not move. Review the solid "
            "measured arm, dashed planned ghost, resolved joint numbers, clearance and warnings. "
            "Only arm_apply_plan or arm_apply_and_look with this one-use id and digest can "
            "execute it before expiry. Prefer arm_apply_and_look when the goal is a photograph."
        ),
    }
    content: list[dict[str, Any]] = [_text(json.dumps(payload, indent=1))]
    if isinstance(plan.get("scene"), dict):
        rendered = _render_plan_jpeg(plan)
        frame_id = f"plan-{int(time.time() * 1000)}-{secrets.token_hex(3)}"
        _keep_frame(frame_id, rendered)
        content.append(
            {
                "type": "image",
                "data": base64.b64encode(rendered).decode("ascii"),
                "mimeType": "image/jpeg",
            }
        )
    return content


def _sequence_waypoint_request(value: Any, index: int) -> dict[str, Any]:
    if not isinstance(value, dict) or not all(isinstance(key, str) for key in value):
        raise ArmToolError(f"waypoint {index} must be an object.")
    allowed = {
        "base",
        "shoulder",
        "elbow",
        "camera",
        "radial_mm",
        "height_mm",
        "elbow_preference",
        "label",
    }
    if set(value) - allowed:
        raise ArmToolError(f"waypoint {index} received an unexpected argument.")

    targets = _requested_targets(value)
    for joint_id, target in targets.items():
        if not math.isfinite(target) or target < PLAN_ANGLE_MIN or target > PLAN_ANGLE_MAX:
            friendly = JOINT_TO_FRIENDLY[joint_id]
            raise ArmToolError(
                f"waypoint {index} {friendly} must be between "
                f"{PLAN_ANGLE_MIN:g} and {PLAN_ANGLE_MAX:g} degrees."
            )
    radial_present = value.get("radial_mm") is not None
    height_present = value.get("height_mm") is not None
    if radial_present != height_present:
        raise ArmToolError(
            f"waypoint {index} radial_mm and height_mm must be supplied together for tip IK."
        )
    tip: dict[str, float] | None = None
    if radial_present:
        radial = _bounded_number(
            value, "radial_mm", PLAN_RADIAL_MIN_MM, PLAN_RADIAL_MAX_MM, required=True
        )
        height = _bounded_number(
            value, "height_mm", PLAN_HEIGHT_MIN_MM, PLAN_HEIGHT_MAX_MM, required=True
        )
        assert radial is not None and height is not None
        if "joint_2" in targets or "joint_3" in targets:
            raise ArmToolError(
                f"waypoint {index} tip IK owns shoulder and elbow. Name only "
                "base/camera alongside radial_mm and height_mm."
            )
        tip = {"radialMm": radial, "heightMm": height}
    if not targets and tip is None:
        raise ArmToolError(
            f"waypoint {index} must name at least one joint or provide radial_mm and height_mm."
        )
    preference = value.get("elbow_preference", "nearest")
    if not isinstance(preference, str) or preference not in {"nearest", "up", "down"}:
        raise ArmToolError(
            f"waypoint {index} elbow_preference must be nearest, up or down."
        )
    request: dict[str, Any] = {
        "targets": targets,
        "elbowPreference": preference,
    }
    label = value.get("label")
    if label is not None:
        if not isinstance(label, str) or not _SAFE_SEQUENCE_LABEL.fullmatch(label):
            raise ArmToolError(
                f"waypoint {index} label must be 1-40 safe letters, numbers, spaces, dots, dashes or underscores."
            )
        request["label"] = label
    if tip is not None:
        request["tip"] = tip
    return request


def tool_arm_plan_sequence(arguments: dict[str, Any]) -> list[dict[str, Any]]:
    """Preview two to eight reviewed poses without moving the physical arm."""

    if set(arguments) != {"waypoints"}:
        raise ArmToolError("arm_plan_sequence needs exactly one waypoints array.")
    waypoints = arguments.get("waypoints")
    if not isinstance(waypoints, list) or not (
        MIN_SEQUENCE_WAYPOINTS <= len(waypoints) <= MAX_SEQUENCE_WAYPOINTS
    ):
        raise ArmToolError(
            f"waypoints must contain between {MIN_SEQUENCE_WAYPOINTS} and "
            f"{MAX_SEQUENCE_WAYPOINTS} poses."
        )
    request = {
        "waypoints": [
            _sequence_waypoint_request(waypoint, index)
            for index, waypoint in enumerate(waypoints)
        ]
    }
    sequence = GATEWAY.json("POST", "/api/robot/arm/sequences/preview", request)
    sequence_id = sequence.get("sequenceId")
    digest = sequence.get("sequenceDigest")
    returned_count = sequence.get("waypointCount")
    returned_waypoints = sequence.get("waypoints")
    if not isinstance(sequence_id, str) or not _SAFE_SEQUENCE_ID.fullmatch(sequence_id):
        raise ArmToolError("The gateway prepared a sequence but returned an invalid sequence id.")
    if not isinstance(digest, str) or not _SAFE_PLAN_DIGEST.fullmatch(digest):
        raise ArmToolError("The gateway prepared a sequence but returned an invalid digest.")
    if (
        isinstance(returned_count, bool)
        or returned_count != len(waypoints)
        or not isinstance(returned_waypoints, list)
        or len(returned_waypoints) != len(waypoints)
    ):
        raise ArmToolError("The gateway prepared a sequence but returned mismatched waypoints.")
    compact_waypoints: list[dict[str, Any]] = []
    for waypoint in returned_waypoints:
        assert isinstance(waypoint, dict)
        compact: dict[str, Any] = {
            key: waypoint.get(key)
            for key in (
                "index",
                "label",
                "resolvedPose",
                "warnings",
                "lowestClearanceMm",
            )
            if key in waypoint
        }
        scene = waypoint.get("scene")
        resolved_scene = scene.get("resolved") if isinstance(scene, dict) else None
        points = (
            resolved_scene.get("points") if isinstance(resolved_scene, dict) else None
        )
        tip_camera = points.get("tipCamera") if isinstance(points, dict) else None
        if isinstance(tip_camera, dict):
            compact["resolvedTipMm"] = tip_camera
        ik = waypoint.get("ik")
        if isinstance(ik, dict):
            compact["ik"] = {
                key: ik.get(key)
                for key in (
                    "target",
                    "projectedTarget",
                    "projected",
                    "elbowPreference",
                    "selectedBranch",
                )
                if key in ik
            }
        compact_waypoints.append(compact)
    payload = {
        key: sequence.get(key)
        for key in (
            "sequenceId",
            "sequenceDigest",
            "expiresAt",
            "expiresInMs",
            "previewDurationMs",
            "measuredPose",
            "waypointCount",
            "warnings",
            "lowestClearanceMm",
        )
        if key in sequence
    }
    payload.update({
        "waypoints": compact_waypoints,
        "note": (
            "PREVIEW ONLY: the arm did not move. Review every waypoint's resolved pose, "
            "transition clearance and warnings. arm_apply_sequence can consume this one "
            "reviewed sequence before expiry, with an optional final camera view."
        ),
    })
    return [_text(json.dumps(payload, indent=1))]


def _sequence_read_timeout_seconds(arrival_timeout_ms: int) -> float:
    return max(
        READ_TIMEOUT_SECONDS,
        MAX_SEQUENCE_WAYPOINTS * arrival_timeout_ms / 1000.0
        + SEQUENCE_TIMEOUT_OVERHEAD_SECONDS,
    )


def _proved_sequence_waypoints(result: dict[str, Any], sequence_id: str) -> int:
    if result.get("sequenceId") != sequence_id or result.get("executed") is not True:
        raise ArmToolError(
            "The combined arm sequence returned a mismatched or unexecuted result."
        )
    operation_id = result.get("operationId")
    if (
        not isinstance(operation_id, str)
        or not _SAFE_SEQUENCE_OPERATION_ID.fullmatch(operation_id)
        or not isinstance(result.get("resolvedPose"), dict)
        or not isinstance(result.get("finalMeasuredPose"), dict)
    ):
        raise ArmToolError("The arm sequence returned an invalid terminal operation receipt.")
    completed = result.get("completedWaypointCount")
    waypoint_count = result.get("waypointCount")
    failed = result.get("failedWaypointIndex")
    waypoint_results = result.get("waypointResults")
    if (
        isinstance(completed, bool)
        or not isinstance(completed, int)
        or isinstance(waypoint_count, bool)
        or not isinstance(waypoint_count, int)
        or not MIN_SEQUENCE_WAYPOINTS <= waypoint_count <= MAX_SEQUENCE_WAYPOINTS
        or completed != waypoint_count
        or failed is not None
        or not isinstance(waypoint_results, list)
        or len(waypoint_results) != waypoint_count
    ):
        raise ArmToolError("The arm sequence returned incomplete terminal waypoint evidence.")
    for index, waypoint in enumerate(waypoint_results):
        arrival = waypoint.get("arrival") if isinstance(waypoint, dict) else None
        if (
            not isinstance(waypoint, dict)
            or waypoint.get("index") != index
            or waypoint.get("outcome") != "arrived"
            or waypoint.get("dispatched") is not True
            or not isinstance(arrival, dict)
            or arrival.get("proved") is not True
        ):
            raise ArmToolError(
                f"The arm sequence did not prove measured arrival at waypoint {index}."
            )
    return completed


def _compact_sequence_failure(result: dict[str, Any]) -> str:
    """Keep the actionable terminal row even when an eight-step receipt is large."""

    failed_index = result.get("failedWaypointIndex")
    rows = result.get("waypointResults")
    failed_row: dict[str, Any] | None = None
    if isinstance(rows, list):
        for candidate in rows:
            if (
                isinstance(candidate, dict)
                and isinstance(failed_index, int)
                and not isinstance(failed_index, bool)
                and candidate.get("index") == failed_index
            ):
                failed_row = candidate
                break
        if failed_row is None and rows and isinstance(rows[-1], dict):
            failed_row = rows[-1]

    evidence: dict[str, Any] = {}
    for name in (
        "operationId",
        "sequenceId",
        "executed",
        "outcome",
        "waypointCount",
        "completedWaypointCount",
        "failedWaypointIndex",
        "durationMs",
        "inspectionRequired",
        "captureAttempted",
    ):
        value = result.get(name)
        if isinstance(value, (str, int, float, bool)) or value is None:
            if not isinstance(value, float) or math.isfinite(value):
                evidence[name] = value
    if failed_row is not None:
        compact_row: dict[str, Any] = {}
        for name in (
            "index",
            "label",
            "outcome",
            "dispatchMs",
            "arrivalMs",
            "durationMs",
        ):
            value = failed_row.get(name)
            if isinstance(value, (str, int, float, bool)) or value is None:
                if not isinstance(value, float) or math.isfinite(value):
                    compact_row[name] = value
        arrival = failed_row.get("arrival")
        if isinstance(arrival, dict):
            compact_arrival: dict[str, Any] = {}
            for name in (
                "proved",
                "reason",
                "lastSampleReason",
                "elapsedMs",
                "sampleCount",
                "stableForMs",
            ):
                value = arrival.get(name)
                if isinstance(value, (str, int, float, bool)) or value is None:
                    if not isinstance(value, float) or math.isfinite(value):
                        compact_arrival[name] = value
            compact_row["arrival"] = compact_arrival
        evidence["failedWaypoint"] = compact_row
    return json.dumps(evidence, separators=(",", ":"), allow_nan=False)[:2_000]


def tool_arm_apply_sequence(arguments: dict[str, Any]) -> list[dict[str, Any]]:
    """Consume one reviewed sequence and let the Pi own every arrival wait."""

    allowed = {"sequence_id", "sequence_digest", "arrival_timeout_ms", "view"}
    if set(arguments) - allowed:
        raise ArmToolError("arm_apply_sequence received an unexpected argument.")
    sequence_id = arguments.get("sequence_id")
    digest = arguments.get("sequence_digest")
    if not isinstance(sequence_id, str) or not _SAFE_SEQUENCE_ID.fullmatch(sequence_id):
        raise ArmToolError("sequence_id is not a valid opaque arm sequence id.")
    if not isinstance(digest, str) or not _SAFE_PLAN_DIGEST.fullmatch(digest):
        raise ArmToolError(
            "sequence_digest must be the sha256 digest returned by arm_plan_sequence."
        )
    requested_timeout = arguments.get("arrival_timeout_ms", DEFAULT_ARRIVAL_TIMEOUT_MS)
    if (
        isinstance(requested_timeout, bool)
        or not isinstance(requested_timeout, int)
        or not 500 <= requested_timeout <= MAX_ARRIVAL_TIMEOUT_MS
    ):
        raise ArmToolError(
            f"arrival_timeout_ms must be an integer between 500 and {MAX_ARRIVAL_TIMEOUT_MS}."
        )
    view = arguments.get("view")
    if view is not None and (
        not isinstance(view, str) or view not in {"survey", "detail"}
    ):
        raise ArmToolError("view must be survey or detail when requesting a final photograph.")
    path = (
        "/api/robot/arm/sequences/execute-and-capture"
        if view is not None
        else "/api/robot/arm/sequences/execute"
    )
    execute_payload: dict[str, Any] = {
        "sequenceId": sequence_id,
        "sequenceDigest": digest,
        "arrivalTimeoutMs": requested_timeout,
    }
    if view is not None:
        execute_payload["captureProfile"] = view
    result = GATEWAY.json(
        "POST",
        path,
        execute_payload,
        read_timeout_seconds=_sequence_read_timeout_seconds(requested_timeout),
    )
    expected_outcome = "captured" if view is not None else "completed"
    if result.get("outcome") != expected_outcome:
        evidence = _compact_sequence_failure(result)
        raise ArmToolError(
            f"The reviewed arm sequence ended with {result.get('outcome')!r}; "
            f"expected {expected_outcome!r}. Evidence: {evidence}"
        )
    completed = _proved_sequence_waypoints(result, sequence_id)
    if view is not None:
        capture = result.get("capture")
        pose_near_capture = result.get("measuredPoseNearCapture")
        if result.get("captureAttempted") is not True or not isinstance(capture, dict):
            raise ArmToolError(
                "The Pi proved the sequence arrivals but returned no usable final capture."
            )
        if not isinstance(pose_near_capture, dict):
            raise ArmToolError(
                "The Pi returned a final frame without typed pose-bound capture evidence."
            )
        return _camera_frame_content(
            capture,
            view,
            pose_near_capture=pose_near_capture,
            extra_context={
                "operationId": result.get("operationId"),
                "executed": True,
                "outcome": "captured",
                "sequenceId": sequence_id,
                # Keep the same terminal timing receipt that the motion-only
                # form returns. Timing and operator evidence must not lose
                # the Pi-owned per-waypoint timings merely because the final
                # waypoint also requested a photograph.
                "durationMs": result.get("durationMs"),
                "waypointCount": result.get("waypointCount"),
                "completedWaypointCount": completed,
                "failedWaypointIndex": None,
                "waypointResults": result.get("waypointResults"),
                "resolvedPose": result.get("resolvedPose"),
                "finalMeasuredPose": result.get("finalMeasuredPose"),
            },
            require_one_use_transfer=True,
        )
    payload = {
        **result,
        "note": (
            f"The Pi executed one reviewed sequence and proved measured arrival at all "
            f"{completed} waypoints. This terminal receipt replaces model-driven sleeps "
            "and intermediate state polls."
        ),
    }
    return [_text(json.dumps(payload, indent=1))]


